/**
 * @file main.c
 * @brief Демонстрация библиотеки LED на CH32V003 (WCH NoneOS SDK).
 *
 * =====================================================================
 *  АППАРАТНАЯ КОНФИГУРАЦИЯ
 * =====================================================================
 *
 *   МК:        CH32V003F4P6 (RISC-V 48 МГц, 16 КБ Flash, 2 КБ RAM)
 *   Диоды:     PC4 (LED0), PC5 (LED1), PC6 (LED2), PC7 (LED3)
 *   Уровень:   HIGH (1 = горит)
 *   Питание:   3.3В
 *
 * =====================================================================
 *  СТРУКТУРА ПРОГРАММЫ
 * =====================================================================
 *
 *   1) Определяем последовательности (массивы шагов).
 *   2) В main():
 *      a) Инициализируем систему (SystemCoreClock, Delay).
 *      b) Настраиваем GPIO (все 4 пина как push-pull output).
 *      c) Инициализируем библиотеку LED.
 *      d) Устанавливаем callback для GPIO.
 *      e) Запускаем demo-сценарий на 3 диодах.
 *      f) В бесконечном цикле: led_process() + Delay_Ms(16).
 *
 * =====================================================================
 *  ДЕМО-СЦЕНАРИЙ
 * =====================================================================
 *
 *   LED0: непрерывное мигание (250 мс вкл / 250 мс выкл)
 *   LED1: включён на 5 секунд, потом выключается
 *   LED2: воспроизведение SOS (... --- ...)
 *   LED3: выключен (не используется)
 *
 * Все 3 эффекта работают ПАРАЛЛЕЛЬНО и НЕЗАВИСИМО.
 *
 * =====================================================================
 *  ЧАСТОТА ОБНОВЛЕНИЯ
 * =====================================================================
 *
 *   led_process() вызывается каждые 16 мс ≈ 60 раз в секунду.
 *   Это определяет временную точность библиотеки:
 *     - 1 тик = 16 мс
 *     - led_blink(0, 15, 15) → 250 мс вкл / 250 мс выкл
 *     - led_on_for(1, 300)   → 300 × 16 мс = 4.8 сек
 *
 *   Задержка реализована через Delay_Ms() из WCH SDK (блокирующая,
 *   калиброванная по SysTick). Для приложений с жёсткими
 *   ограничениями по времени можно заменить на аппаратный таймер.
 */

#include "led.h"
#include "gpio_setup.h"
#include "ch32v00x.h"
#include "debug.h"

/* ================================================================== */
/*  ПРЕДОПРЕДЕЛЁННЫЕ ПОСЛЕДОВАТЕЛЬНОСТИ                                  */
/* ================================================================== */

/**
 * SOS: ... --- ...
 *
 * Стандартный сигнал бедствия:
 *   . (точка)   = 6 тиков ON  (100 мс)
 *   - (тире)    = 18 тиков ON (300 мс)
 *   пауза между элементами = 6 тиков (100 мс)
 *   пауза между буквами    = 18 тиков (300 мс)
 *   пауза между повторами  = 60 тиков (1 сек)
 *
 * Одна буква S: 3 точки + паузы = 6×6 = 36 тиков (600 мс)
 * Одна буква O: 3 тире + паузы = 3×18 + 2×6 = 66 тиков (1.1 сек)
 * Одна буква S: 3 точки + паузы = 6×6 = 36 тиков (600 мс)
 * Пауза между повторами: 60 тиков (1 сек)
 * Итого один цикл SOS: ~3.3 сек
 */
static const led_step_t sos_steps[] = {
    /* Буква S: ... */
    LED_STEP_ON(6),   LED_STEP_OFF(6),     /* . */
    LED_STEP_ON(6),   LED_STEP_OFF(6),     /* . */
    LED_STEP_ON(6),   LED_STEP_OFF(18),    /* . (пауза перед O) */

    /* Буква O: --- */
    LED_STEP_ON(18),  LED_STEP_OFF(6),     /* - */
    LED_STEP_ON(18),  LED_STEP_OFF(6),     /* - */
    LED_STEP_ON(18),  LED_STEP_OFF(18),    /* - (пауза перед S) */

    /* Буква S: ... */
    LED_STEP_ON(6),   LED_STEP_OFF(6),     /* . */
    LED_STEP_ON(6),   LED_STEP_OFF(6),     /* . */
    LED_STEP_ON(6),   LED_STEP_OFF(60),    /* . (пауза между повторами) */
};

/**
 * Определение последовательности SOS.
 *
 * steps  — массив шагов выше
 * count  — автоматически вычисляется через sizeof
 * loop   = true — повторять бесконечно
 */
static const led_sequence_t sos = {
    sos_steps,
    sizeof(sos_steps) / sizeof(sos_steps[0]),
    true
};

/* ================================================================== */
/*  ТОЧКА ВХОДА                                                        */
/* ================================================================== */

int main(void)
{
    /*
     * SystemCoreClockUpdate() — пересчитывает переменную SystemCoreClock
     * на основе текущих регистров RCC. После SystemInit() (вызывается
     * из startup) PLL уже настроен на 48 МГц, но переменная может быть
     * неактуальной. Эта функция синхронизирует её.
     */
    SystemCoreClockUpdate();

    /*
     * Delay_Init() — инициализация блокирующей задержки.
     * Вычисляет количество тиков SysTick на микросекунду.
     * Нужна для Delay_Ms() ниже.
     */
    Delay_Init();

    /*
     * gpio_init_leds() — настройка GPIO:
     *   - Включить тактирование порта C
     *   - PC4-PC7: 2 МГц push-pull output
     *   - Все 4 пина: начальное состояние LOW (диоды выключены)
     */
    gpio_init_leds();

    /*
     * led_init() — сброс библиотеки:
     *   - Все 4 LED → режим OFF
     *   - Все счётчики → 0
     *   - Callback → NULL
     *   - Глобальный тик → 0
     */
    led_init();

    /*
     * led_set_callback() — регистрация callback-функции для GPIO.
     * Библиотека будет вызывать led_hw_set(id, state) при каждом
     * изменении состояния диода. led_hw_set() определена в gpio_setup.c
     * и переключает соответствующий пин (PC4+id).
     */
    led_set_callback(led_hw_set);

    /* ================================================================== */
    /*  ДЕМО-СЦЕНАРИЙ                                                     */
    /* ================================================================== */

    /*
     * LED0: непрерывное мигание.
     *   15 тиков ON  = 250 мс (при 60 Гц: 15 × 16.67 мс)
     *   15 тиков OFF = 250 мс
     *   Период: 500 мс, скважность: 50%
     */
    //led_blink(0, 15, 15);

    /*
     * LED1: включить на 300 тиков (5 секунд).
     *   300 × 16.67 мс ≈ 5 сек
     *   После истечения времени диод автоматически выключится.
     */
    //led_on_for(1, 300);

    /*
     * LED2: воспроизвести SOS-последовательность.
     *   См. описание sos_steps[] выше.
     *   loop = true — повторять бесконечно.
     */
    led_play(2, &sos);

    /* Бегущий огонь один раз (4 позиции: 0→1→2→3, потом все гаснут) */
    //led_start_effect_for(LED_EFFECT_RUNNING_FWD, 1);

    /* Вспышка 4 диодов с последовательным погасанием */
    //led_flash_and_fade(4);

    /* ================================================================== */
    /*  ГЛАВНЫЙ ЦИКЛ                                                      */
    /* ================================================================== */

    /*
     * Бесконечный цикл:
     *   1) led_process() — обработать все 4 LED за один тик.
     *      Время выполнения: < 100 мкс (константное).
     *   2) Delay_Ms(16) — ждать 16 мс до следующего тика.
     *      Частота: 1000 / 16 ≈ 62.5 Гц (≈ 60 Гц).
     *
     * Примечание: Delay_Ms() — блокирующая задержка. MCU простаивает
     * (выполняет NOP) в течение 16 мс. Для приложений, требующих
     * мультизадачности, можно заменить на:
     *   - SysTick прерывание (как в первоначальной версии)
     *   - Таймер с DMA
     *   - RTOS (если нужен)
     */
    while (1) {
        led_process();
        Delay_Ms(16);
    }

    return 0;
}
