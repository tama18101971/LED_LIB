/*  ПУБЛИЧНЫЙ API: жизненный цикл                                      */
/* ================================================================== */

/**
 * Инициализация библиотеки.
 *
 * Сбрасывает все каналы в режим OFF, обнуляет счётчики и генератор
 * случайных чисел, останавливает эффект, снимает владение
 * индикатором.
 *
 * Ранее установленный callback СОХРАНЯЕТСЯ, а кэш выводов
 * инвалидируется — на ближайшем led_advance() все выводы будут
 * принудительно перезаписаны. Чтобы отключить вывод, вызовите
 * led_set_callback(NULL).
 */
void led_init(void);

/**
 * Установка callback-функции для доступа к выводу.
 *
 * Инвалидирует кэш уровней: новый callback получит полную картину
 * (по одному вызову на каждый канал) на ближайшем led_advance().
 *
 * @param fn  Функция записи в вывод; NULL = отключить вывод.
 */
void led_set_callback(led_set_fn fn);

/**
 * Принудительная пересинхронизация выводов.
 *
 * Инвалидирует кэш уровней, не меняя логическое состояние каналов.
 * Нужна, если выводы могли измениться в обход библиотеки:
 * переинициализация порта, выход из режима сна, смена альтернативной
 * функции пина. На следующем led_advance() все каналы будут записаны
 * заново (теми же уровнями).
 */
void led_refresh(void);

/**
 * ГЛАВНАЯ ФУНКЦИЯ — продвижение времени.
 *
 * Контракт: после возврата состояние всех выводов соответствует
 * времени t+ticks. Если за один вызов пересечено несколько переходов,
 * они применяются все и по порядку (детерминированно, без «провала»
 * переходов).
 *
 * Инвариант против дрейфа: led_advance(1) × N и led_advance(N) дают
 * ИДЕНТИЧНУЮ последовательность вызовов callback и одинаковое
 * конечное состояние.
 *
 * Никаких внутренних источников времени: библиотека не знает, кто её
 * будит. Критической секцией НЕ оборачивается (намеренно).
 *
 * Внутри: для каждого канала в ручном режиме и для глобальных
 * паттернов (эффект, упакованные команды) обрабатываются переходы;
 * тики без переходов проматываются за O(1) на тик.
 *
 * @param ticks  Число тиков (0 = ничего не делать).
 */
void led_advance(uint32_t ticks);

/**
 * Число тиков до ближайшего ИЗМЕНЕНИЯ состояния вывода.
 *
 * Это «сколько можно спать»: хост программирует свой таймер
 * пробуждения на это число тиков, засыпает, затем вызывает
 * led_advance(elapsed_ticks).
 *
 * Возвращает LED_TICKS_FOREVER, если таймерных паттернов нет (все
 * каналы в статичных режимах) — изменений не будет без нового вызова
 * API. Значение 0 не возвращается: стартовые мутаторы применяют первое
 * состояние немедленно.
 *
 * Возвращается минимум по всем активным паттернам.
 */
uint32_t led_ticks_until_next(void);

/**
 * Совместимость с 2.x: один тик. Определено как led_advance(1).
 *
 * Вызывать с постоянной частотой (обычно 60 раз в секунду).
 */
void led_process(void);

