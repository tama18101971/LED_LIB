/**
 * Количество управляемых светодиодов (1..8).
 *
 * Переопределяется из сборочной системы, например:
 *   build_flags = -DLED_COUNT=6
 *
 * Верхняя граница — 8: внутренние маски состояний имеют тип uint8_t.
 * Все встроенные эффекты (включая паттерны «все» и «чёт/нечет»)
 * автоматически подстраиваются под выбранное значение.
 */
#ifndef LED_COUNT
#define LED_COUNT 4
#endif

#if (LED_COUNT < 1) || (LED_COUNT > 8)
#error "LED_COUNT must be in range 1..8: internal state bitmasks are uint8_t"
#endif

/**
 * Опциональные модули. Установите 0, чтобы полностью исключить
 * соответствующий код из сборки (экономия Flash на малых МК).
 *
 *   LED_USE_SEQUENCES           — led_play() и режим SEQUENCE
 *                                 (также убирает 4 поля из состояния LED)
 *   LED_USE_EFFECTS             — вся подсистема глобальных эффектов
 *   LED_USE_RUNNING_EFFECTS     — RUNNING_FWD / BWD / CIRCLE
 *   LED_USE_PINGPONG_EFFECT     — RUNNING_PP (требует LED_COUNT >= 2)
 *   LED_USE_BLINK_EFFECTS       — EMERGENCY / PAIR_BLINK / ALTERNATING
 *   LED_USE_MULTI_BLINK_EFFECTS — DOUBLE_BLINK / TRIPLE_BLINK
 *   LED_USE_RANDOM_EFFECT       — RANDOM_FLASH
 *   LED_USE_HOLD_EFFECTS        — RUNNING_FWD_HOLD / RUNNING_BWD_HOLD
 *
 * Значения enum led_effect_t не меняются при отключении модулей, поэтому
 * ABI остаётся стабильным. Попытка запустить отключённый эффект
 * игнорируется (led_start_effect() возвращает управление без действий).
 */
#ifndef LED_USE_SEQUENCES
#define LED_USE_SEQUENCES 1
#endif

#ifndef LED_USE_EFFECTS
#define LED_USE_EFFECTS 1
#endif

#ifndef LED_USE_RUNNING_EFFECTS
#define LED_USE_RUNNING_EFFECTS 1
#endif

#ifndef LED_USE_PINGPONG_EFFECT
#define LED_USE_PINGPONG_EFFECT (LED_COUNT >= 2)
#endif

#ifndef LED_USE_BLINK_EFFECTS
#define LED_USE_BLINK_EFFECTS 1
#endif

#ifndef LED_USE_MULTI_BLINK_EFFECTS
#define LED_USE_MULTI_BLINK_EFFECTS 1
#endif

#ifndef LED_USE_RANDOM_EFFECT
#define LED_USE_RANDOM_EFFECT 1
#endif

#ifndef LED_USE_HOLD_EFFECTS
#define LED_USE_HOLD_EFFECTS 1
#endif

#if LED_USE_PINGPONG_EFFECT && (LED_COUNT < 2)
#error "LED_USE_PINGPONG_EFFECT requires LED_COUNT >= 2"
#endif

/**
 * Критическая секция для защиты мутаторов от вытеснения led_process().
 * По умолчанию — пустышки (сценарий «всё из одного контекста»).
 * См. раздел «МОДЕЛЬ ВЫЗОВОВ И ПОТОКОБЕЗОПАСНОСТЬ» выше.
 */
#ifndef LED_ENTER_CRITICAL
#define LED_ENTER_CRITICAL() ((void)0)
#endif

#ifndef LED_EXIT_CRITICAL
#define LED_EXIT_CRITICAL() ((void)0)
#endif

