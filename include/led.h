/**
 * Текущий режим диода.
 *
 * @param id  Индекс диода (0..LED_COUNT-1).
 * @return Режим; LED_MODE_OFF для индекса вне диапазона.
 */
led_mode_t led_get_mode(uint8_t id);

/**
 * Горит ли диод в данный момент (последнее состояние, отданное в GPIO).
 *
 * @param id  Индекс диода (0..LED_COUNT-1).
 * @return 1 — включён, 0 — выключен или индекс вне диапазона.
 */
uint8_t led_is_on(uint8_t id);

/**
 * Есть ли хотя бы один диод в «занятом» режиме
 * (ON_FOR, BLINK, SEQUENCE или EFFECT).
 *
 * @return 1 — идёт индикация, 0 — все диоды в статичном режиме.
 */
uint8_t led_any_led_active(void);

