/**
 * @file led.h
 * @brief Библиотека управления индикацией для bare-metal микроконтроллеров
 *        (без RTOS). Версия 3.0.
 *
 * =====================================================================
 *  АРХИТЕКТУРА
 * =====================================================================
 *
 * Тик — единица времени, задаваемая ХОСТОМ. Хост сам решает, когда
 * двигать время вперёд, и может спать между продвижениями:
 *
 *   void led_advance(uint32_t ticks);   // продвинуть все FSM на ticks тиков
 *   uint32_t led_ticks_until_next(void);// тиков до ближайшего ИЗМЕНЕНИЯ вывода
 *
 * Это единственная модель времени в библиотеке. Внутренних источников
 * времени нет: библиотека не знает, кто её будит (аппаратный таймер
 * пробуждения, STANDBY, RTOS-задача, обычный опрос 60 Гц).
 *
 * =====================================================================
 *  СПЯЩИЙ ХОСТ (рецепт)
 * =====================================================================
 *
 *     while (led_ticks_until_next() != LED_TICKS_FOREVER) {
 *         program_your_timer(led_ticks_until_next());  // тик = ваша единица
 *         sleep();
 *         led_advance(elapsed_ticks);
 *     }
 *
 * Контракт: после возврата из led_advance(n) состояние всех выходов
 * соответствует времени t+n. Если за один advance пересечено несколько
 * переходов, они применяются ВСЕ и ПО ПОРЯДКУ (через callback) — выход
 * не «пропускает» переходы. Поэтому led_advance(1) × N и led_advance(N)
 * дают идентичную последовательность вызовов callback и одинаковое
 * конечное состояние.
 *
 * Тик — единица пользователя: 1 мс, 1/60 с, 1/1000 с. Библиотека не
 * знает и не пересчитывает его в физическое время.
 *
 * =====================================================================
 *  УРОВНИ ВЫХОДА (не только вкл/выкл)
 * =====================================================================
 *
 * Выход каждого канала — это УРОВЕНЬ 0..LED_LEVEL_MAX, а не bool.
 *   level 0        — выключено
 *   level 1..N     — включено с яркостью/режимом N (интерпретация —
 *                    забота callback'а: GPIO-включитель, DAC, ШИМ)
 * Типичный применение: основной светодиод через DAC с 7 ступенями
 * яркости, плюс два булевых канала. Библиотека оперирует числами и
 * ничего не знает про DAC.
 *
 * =====================================================================
 *  ВЛАДЕНИЕ ИНДИКАТОРОМ
 * =====================================================================
 *
 * Индикатор один, но управляют им несколько подсистем (обычная
 * индикация, маяк, предупреждение о напряжении, строб). Арбитраж —
 * на уровне подсистемы, а не на уровне вывода:
 *
 *     led_set_owner(LED_OWNER_BEACON);   // «это моё»
 *     if (led_claim() == LED_OWNER_NONE) { led_packed_run(beacon, 4); }
 *     ...
 *     if (led_stop_owner(LED_OWNER_BEACON)) { ...остановил только своё... }
 *
 * Владение глобальное для подсистемы, НЕ per-LED: маяк умеет гасить
 * «своё» целиком, не затрагивая чужое. Владение автоматически
 * сбрасывается в LED_OWNER_NONE, когда все таймерные паттерны
 * завершились.
 *
 * =====================================================================
 *  КАЖДЫЙ СВЕТОДИОД ИМЕЕТ СОБСТВЕННЫЙ КОНЕЧНЫЙ АВТОМАТ
 * =====================================================================
 *
 * Это позволяет одновременно:
 *   - мигать одному диоду,
 *   - воспроизводить SOS на другом,
 *   - держать третий включённым на 5 секунд,
 *   - четвёртый — выключенным.
 *
 * Глобальные эффекты (бегущий огонь, аварийная сигнализация и т.д.)
 * управляются через таблицу функций в led.c. Каждый эффект — функция,
 * возвращающая битовую маску желаемых состояний диодов.
 *
 * Последовательности (sequences) определяются статическими массивами
 * через макросы LED_STEP_ON() / LED_STEP_OFF() / LED_STEP_LVL().
 *
 * Упакованные команды (LED_USE_PACKED_COMMANDS) — компактный формат
 * «4 байта на пару фаз + счётчик повторов» для хостов, у которых
 * экономия Flash/RAM критична (см. раздел УПАКОВАННЫЕ КОМАНДЫ).
 *
 * =====================================================================
 *  МОДЕЛЬ ВЫЗОВОВ И ПОТОКОБЕЗОПАСНОСТЬ
 * =====================================================================
 *
 * Внутреннее состояние — обычные static-переменные без блокировок.
 * Поддерживаются два сценария:
 *
 *  1) ОДИН КОНТЕКСТ (по умолчанию). Все led_*() вызываются из одного
 *     места — обычно из главного цикла. Настройка не требуется.
 *
 *  2) led_advance() В ПРЕРЫВАНИИ, остальной API — из главного цикла.
 *     Определите LED_ENTER_CRITICAL()/LED_EXIT_CRITICAL() (запрет и
 *     восстановление прерываний), чтобы мутаторы стали атомарными
 *     относительно обработчика. Пример для CH32V003 / RISC-V:
 *
 *       #define LED_ENTER_CRITICAL()  __disable_irq()
 *       #define LED_EXIT_CRITICAL()   __enable_irq()
 *
 *     Внимание: при заданных макросах пользовательские callback'и
 *     (вывода и событий) могут вызываться с запрещёнными прерываниями —
 *     держите их короткими.
 *
 *  НЕ ПОДДЕРЖИВАЕТСЯ: вызов мутаторов (led_on/led_blink/led_play/…)
 *  из прерывания, когда led_advance() работает в главном цикле —
 *  состояние конечного автомата будет повреждено. led_advance()
 *  критической секцией НЕ оборачивается намеренно: это сохраняет
 *  минимальную задержку реакции на прерывания.
 *
 * =====================================================================
 *  ОГРАНИЧЕНИЯ
 * =====================================================================
 *
 *   - Библиотека НЕ содержит код GPIO/таймеров — доступ к выводам
 *     только через пользовательский callback (led_set_fn).
 *   - Нет malloc/free/рекурсии и зависимости от libc — только
 *     статическая память.
 *   - В горячем пути нет ни деления, ни умножения (кроме разбора
 *     упакованной команды, где это сдвиги). Деление/умножение есть
 *     только в МАКРОСАХ кодирования, которые сворачиваются в константы
 *     времени компиляции.
 *   - Портабельность: C99, без расширений компилятора.
 *
 * =====================================================================
 *  СОВМЕСТИМОСТЬ
 * =====================================================================
 *
 *   Tested / designed for: STM32, CH32V003, AVR, ESP32.
 *   Любой bare-metal MCU с таймером пробуждения или delay-функцией
 *   подходит.
 *
 * =====================================================================
 *  СОВМЕСТИМОСТЬ С 2.x
 * =====================================================================
 *
 * 3.0 — breaking-релиз:
 *   - led_set_fn: (uint8_t id, bool state) → (uint8_t id, uint8_t level);
 *   - led_step_t.state (bool) → led_step_t.level (uint8_t);
 *   - новая led_blink_level() и led_set_level();
 *   - новая событийная модель времени led_advance()/led_ticks_until_next()
 *     (led_process() сохранён как led_advance(1));
 *   - новое владение индикатором, упакованные команды, события.
 * Миграция — см. CHANGELOG.md, раздел 3.0.0.
 */

