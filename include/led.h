/* ================================================================== */
/*  УПАКОВАННЫЕ КОМАНДЫ (R5)                                           */
/* ================================================================== */

/**
 * =====================================================================
 *  Компактный формат паттерна: 32 бита на пару фаз + счётчик повторов
 * =====================================================================
 *
 * Для хостов, у которых каждый байт Flash/RAM на счет: обычная
 * последовательность стоит 4 байта на ФАЗУ, упакованная команда —
 * 4 байта на пару фаз вместе со счётчиком повторов и маской каналов.
 *
 * Раскладка битов (жёстко зафиксирована, изменение сломает ABI):
 *
 *   [3:0]   device    — битовая маска каналов (0..15, лишние отсекаются)
 *   [7:4]   count     — число повторов пары фаз; 15 = бесконечно
 *   [10:8]  shift0    — порядок масштаба длительности фазы 0 (0..7)
 *   [16:11] win0      — мантисса длительности фазы 0 (0..63)
 *   [19:17] shift1    — порядок масштаба длительности фазы 1 (0..7)
 *   [25:20] win1      — мантисса длительности фазы 1 (0..63)
 *   [28:26] level0    — уровень фазы 0 (0 = off, 1..7)
 *   [31:29] level1    — уровень фазы 1
 *
 * Длительность (в ТИКАХ, не в регистрах таймера — библиотека остаётся
 * hardware-agnostic):
 *
 *     duration = (1 << (2 * shift)) * win
 *
 * shift 0..7 → ×1, ×4, ×16, ×64, ×256, ×1024, ×4096, ×16384;
 * win 0..63, при win == 0 фаза «без ожидания» (нулевая длительность).
 * Диапазон 1..1032192 тиков. Значения до 63 тиков кодируются ТОЧНО
 * (shift = 0, win = ticks). Для остальных значений действует
 * round-to-nearest: относительная погрешность не хуже 1/32 ≈ 3.1 % —
 * это теоретический предел для 6-битной мантиссы при шаге 4^shift
 * (мантисса всегда в диапазоне 16..63, шаг квантования — ticks/16,
 * ошибка округления — половина шага). Максимум достигается сразу над
 * границей диапазона (например, 4065 тиков -> 4096, т.е. +0.76 %).
 * Время задаётся в тиках, а не в миллисекундах, поэтому точность
 * кодирования длительностей не влияет на работу паттернов.
 *
 * Системные команды: биты 5..31 == 0, op[1:0], steps[4:2].
 * Нулевое слово — это LED_SYS_STOP.
 *
 *   static const uint32_t beacon[] = {
 *       LED_CMD(0x1, 1, 15,  60, 3, 0),   // одна вспышка уровня 3
 *       LED_CMD(0x1, 1, 15, 420, 3, 0),   // вторая, с длинной паузой
 *       LED_CMD(0x1, 1, 15,  60, 3, 0),   // третья
 *       LED_SYS_REP_START                 // повторять до снятия владения
 *   };
 *   led_packed_run(beacon, LED_ARRAY_LEN(beacon));
 */

/** Кодирование длительности (в тиках) в 9-битное поле (shift:6 | win:6). */
#define LED_TIME_ENC(t)                                                      \
    ((uint32_t)(                                                             \
        ((t) <= 63u)     ? (0u << 6) | (t)                                    \
      : ((t) <= 252u)    ? ((1u << 6) | (((t) + 2u) / 4u))                  \
      : ((t) <= 1008u)   ? ((2u << 6) | (((t) + 8u) / 16u))                 \
      : ((t) <= 4032u)   ? ((3u << 6) | (((t) + 32u) / 64u))                \
      : ((t) <= 16128u)  ? ((4u << 6) | (((t) + 128u) / 256u))              \
      : ((t) <= 64512u)  ? ((5u << 6) | (((t) + 512u) / 1024u))             \
      : ((t) <= 258048u) ? ((6u << 6) | (((t) + 2048u) / 4096u))            \
      : ((7u << 6) | ((((t) + 8192u) / 16384u > 63u) ? 63u                   \
                                                  : (((t) + 8192u) / 16384u)))))

/**
 * Собрать упакованную команду.
 *
 * @param dev   Битовая маска каналов (0..15).
 * @param count Число повторов пары фаз (0..15; 15 = бесконечно).
 * @param t0    Длительность фазы 0 в тиках (0 = без ожидания).
 * @param t1    Длительность фазы 1 в тиках (0 = без ожидания).
 * @param lvl0  Уровень фазы 0 (0 = off, 1..7).
 * @param lvl1  Уровень фазы 1 (0 = off, 1..7).
 *
 * Пример: «3 коротких вспышки по 15 тиков, пауза 60 тиков, уровень 1»
 *   LED_CMD(1, 3, 15, 60, 1, 0)
 */
#define LED_CMD(dev, count, t0, t1, lvl0, lvl1)                              \
    ((uint32_t)((((dev) & 0x0Fu))                                            \
              | ((((uint32_t)(count)) & 0x0Fu) << 4)                         \
              | ((uint32_t)LED_TIME_ENC(t0) << 8)                             \
              | ((uint32_t)LED_TIME_ENC(t1) << 17)                            \
              | ((((uint32_t)(lvl0)) & 0x7u) << 26)                           \
              | ((((uint32_t)(lvl1)) & 0x7u) << 29)))

/** Маска каналов команды: LED_CMD_DEV(w). */
#define LED_CMD_DEV(w)    ((uint8_t)((w) & 0x0Fu))

/** Счётчик повторов команды: 0..14, 15 = бесконечно. */
#define LED_CMD_COUNT(w)  ((uint8_t)(((w) >> 4) & 0x0Fu))

/** Закодированное поле времени фазы 0 (9 бит: shift<<6 | win). */
#define LED_CMD_T0F(w)    ((uint32_t)(((w) >> 8) & 0x1FFu))

/** Закодированное поле времени фазы 1 (9 бит: shift<<6 | win). */
#define LED_CMD_T1F(w)    ((uint32_t)(((w) >> 17) & 0x1FFu))

/** Порядок масштаба фазы 0 (0..7). */
#define LED_CMD_T0S(w)    ((uint8_t)((((w) >> 8) >> 6) & 0x7u))

/** Мантисса фазы 0 (0..63). */
#define LED_CMD_T0W(w)    ((uint8_t)(((w) >> 8) & 0x3Fu))

/** Порядок масштаба фазы 1 (0..7). */
#define LED_CMD_T1S(w)    ((uint8_t)((((w) >> 17) >> 6) & 0x7u))

/** Мантисса фазы 1 (0..63). */
#define LED_CMD_T1W(w)    ((uint8_t)(((w) >> 17) & 0x3Fu))

/** Длительность фазы 0 в тиках (0 = без ожидания). */
#define LED_CMD_T0(w) \
    ((uint32_t)(((w) >> 8) & 0x3Fu) << (2u * ((((w) >> 8) >> 6) & 0x7u)))

/** Длительность фазы 1 в тиках (0 = без ожидания). */
#define LED_CMD_T1(w) \
    ((uint32_t)(((w) >> 17) & 0x3Fu) << (2u * ((((w) >> 17) >> 6) & 0x7u)))

/** Уровень фазы 0 (0 = off, 1..7). */
#define LED_CMD_LVL0(w)   ((uint8_t)(((w) >> 26) & 0x7u))

/** Уровень фазы 1 (0 = off, 1..7). */
#define LED_CMD_LVL1(w)   ((uint8_t)(((w) >> 29) & 0x7u))

/** Слово является системной командой (биты 5..31 == 0). */
#define LED_CMD_IS_SYS(w)     (((w) >> 5) == 0u)

/** Код операции системной команды: LED_CMD_OP(w). */
#define LED_CMD_OP(w)         ((uint8_t)((w) & 0x3u))

/** Параметр steps системной команды: 0..7. */
#define LED_CMD_STEPS(w)      ((uint8_t)(((w) >> 2) & 0x7u))

/** Слово — системная команда с указанной операцией. */
#define LED_CMD_IS_OP(w, op)  (LED_CMD_IS_SYS(w) && (LED_CMD_OP(w) == (op)))

/** Собрать системную команду. */
#define LED_SYS_CMD(op, steps) \
    ((uint32_t)((((steps) & 0x7u) << 2) | ((op) & 0x3u)))

/** Остановить паттерн (нулевое слово). */
#define LED_SYS_STOP        LED_SYS_CMD(0u, 0u)

/** Повторять массив с первой команды (бесконечно). */
#define LED_SYS_REP_START   LED_SYS_CMD(1u, 0u)

/** Повторить массив ещё n раз (n = 0..7), затем остановиться. */
#define LED_SYS_REP_AT(n)   LED_SYS_CMD(2u, (n))

#if LED_USE_PACKED_COMMANDS
/**
 * Максимальное число системных команд, обрабатываемых за один
 * вызов led_advance(). Защита от вырожденных таблиц, в которых все
 * фазы имеют нулевую длительность (иначе — бесконечный цикл внутри
 * одного advance). Для нормальных таблиц (есть хотя бы одна фаза с
 * длительностью) ограничение недостижимо: каждый проход тратит тики.
 */
#define LED_PACKED_GUARD 16u
#endif

