/**
 * Тип callback-функции для доступа к выводу.
 *
 * Библиотека НЕ обращается к портам напрямую. Вместо этого она вызывает
 * эту функцию, когда уровень выхода ИЗМЕНИЛСЯ (внутренний кэш уровней
 * отсекает повторные записи).
 *
 * Из callback нельзя вызывать функции led_*(): библиотека не реентерабельна.
 *
 * @param id     Индекс канала (0..LED_COUNT-1).
 * @param level  0 = выключить, 1..LED_LEVEL_MAX = уровень вывода.
 *
 * Пример для обычного GPIO-включателя:
 *   void led_hw_set(uint8_t id, uint8_t level) {
 *       if (level) GPIO_SetBits(GPIOC,  (uint16_t)(1UL << (4 + id)));
 *       else      GPIO_ResetBits(GPIOC, (uint16_t)(1UL << (4 + id)));
 *   }
 *
 * Пример для аналогового канала (DAC с N ступенями):
 *   static const uint8_t dac_code[LED_LEVEL_MAX + 1] = {0, 34, 68, ...};
 *   void led_hw_set(uint8_t id, uint8_t level) {
 *       if (level > LED_LEVEL_MAX) level = LED_LEVEL_MAX;
 *       out_set_stc(dac_code[level]);   // 0 = канал выключен
 *   }
 */
typedef void (*led_set_fn)(uint8_t id, uint8_t level);

/**
 * Режим работы конкретного канала (конечный автомат).
 *
 * Каждый канал находится ровно в одном из этих режимов.
 *
 *   LED_MODE_OFF      — принудительно выключен
 *   LED_MODE_ON       — принудительно включён (уровень 1 или иной)
 *   LED_MODE_ON_FOR   — включён на N тиков, потом авто-выключение
 *   LED_MODE_BLINK    — двухфазное мигание (уровни A и B)
 *   LED_MODE_SEQUENCE — воспроизведение пользовательской последовательности
 *   LED_MODE_EFFECT   — управление глобальным эффектом
 *   LED_MODE_PACKED   — управление упакованной командой
 *
 * Для таймерных состояний (ON_FOR, BLINK, SEQUENCE) уровень хранится
 * в том же состоянии канала; EFFECT и PACKED применяют уровень сами.
 */
typedef enum {
    LED_MODE_OFF      = 0,
    LED_MODE_ON       = 1,
    LED_MODE_ON_FOR   = 2,
    LED_MODE_BLINK    = 3,
    LED_MODE_SEQUENCE = 4,
    LED_MODE_EFFECT   = 5,
    LED_MODE_PACKED   = 6   /**< каналы под управлением упакованного паттерна */
} led_mode_t;

/**
 * Встроенные глобальные эффекты.
 *
 * Глобальный эффект управляет ВСЕМИ каналами одновременно.
 * Активируется через led_start_effect(), останавливается
 * через led_stop_effect().
 *
 * При запуске эффекта все каналы переходят в режим LED_MODE_EFFECT.
 * Если пользователь вызовет led_on(id) на одном из каналов,
 * этот канал «оторвётся» от эффекта и будет управляться вручную,
 * а остальные продолжат эффект.
 *
 * Значения enum фиксированы и не зависят от LED_USE_*-настроек.
 */
typedef enum {
    LED_EFFECT_NONE             = 0,  /**< Эффект не активен                 */
    LED_EFFECT_RUNNING_FWD      = 1,  /**< Бегущий огонь вперёд (0→N-1)      */
    LED_EFFECT_RUNNING_BWD      = 2,  /**< Бегущий огонь назад (N-1→0)       */
    LED_EFFECT_RUNNING_PP       = 3,  /**< Бегущий огонь туда-обратно        */
    LED_EFFECT_RUNNING_CIRCLE   = 4,  /**< Вращение по кругу (быстрее FWD)   */
    LED_EFFECT_PAIR_BLINK       = 5,  /**< Попарное мигание (чёт/нечет)      */
    LED_EFFECT_EMERGENCY        = 6,  /**< Аварийная сигнализация (все)      */
    LED_EFFECT_RANDOM_FLASH     = 7,  /**< Случайные вспышки (xorshift32)    */
    LED_EFFECT_DOUBLE_BLINK     = 8,  /**< Двойное мигание                   */
    LED_EFFECT_TRIPLE_BLINK     = 9,  /**< Тройное мигание                   */
    LED_EFFECT_ALTERNATING      = 10, /**< Чередование чёт/нечёт (медленно)  */
    LED_EFFECT_RUNNING_FWD_HOLD = 11, /**< Бег вперёд + пауза + удержание    */
    LED_EFFECT_RUNNING_BWD_HOLD = 12, /**< Бег назад + пауза + удержание     */
    LED_EFFECT_COUNT            = 13  /**< Количество значений (граница)     */
} led_effect_t;

/**
 * Значение «эффект работает бесконечно», возвращаемое
 * led_effect_remaining().
 */
#define LED_EFFECT_FOREVER 0xFFFFFFFFu

/**
 * Значение «изменений вывода не будет без нового вызова API»,
 * возвращаемое led_ticks_until_next().
 */
#define LED_TICKS_FOREVER 0xFFFFFFFFu

/**
 * Один шаг последовательности: уровень + длительность.
 *
 * Порядок полей — level первым, чтобы на RV32 (выравнивание uint16_t = 2)
 * размер структуры остался 4 байта без «дырки» в хвосте.
 *
 * Пример: «уровень 3 на 10 тиков, затем выключение на 5 тиков»
 *   { 3, 10 }   // LED_STEP_LVL(3, 10)
 *   { 0,  5 }   // LED_STEP_OFF(5)
 *
 * Шаг с ticks == 0 трактуется как 1 тик (нулевая длительность
 * невозможна в тиковой модели).
 */
typedef struct {
    uint8_t  level;   /**< Уровень вывода: 0 = off, 1..LED_LEVEL_MAX    */
    uint16_t ticks;   /**< Длительность в тиках (0 → 1)                 */
} led_step_t;

/**
 * Определение последовательности.
 *
 * ВАЖНО: библиотека хранит указатель на массив steps и не копирует его.
 * Массив должен существовать всё время воспроизведения — используйте
 * static/const, а не локальные переменные.
 *
 * Считать длину массива руками не нужно — используйте макросы
 * LED_SEQ() / LED_SEQ_LOOP():
 *
 *   static const led_step_t sos[] = {
 *       LED_STEP_ON(6),  LED_STEP_OFF(6),    // .
 *       LED_STEP_ON(6),  LED_STEP_OFF(6),    // .
 *       LED_STEP_ON(6),  LED_STEP_OFF(18),   // . (пауза)
 *       LED_STEP_ON(18), LED_STEP_OFF(6),    // -
 *       ...
 *   };
 *   static const led_sequence_t seq = LED_SEQ_LOOP(sos);
 *   led_play(2, &seq);                       // воспроизвести на LED2
 */
typedef struct {
    const led_step_t *steps;   /**< Массив шагов (должен «жить» долго) */
    uint16_t          count;   /**< Количество шагов                  */
    bool              loop;    /**< true = зациклить                  */
} led_sequence_t;

