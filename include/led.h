/** Шаг «уровень level на N тиков». */
#define LED_STEP_LVL(level, ticks)  { (level), (ticks) }

/** Шаг «включить (уровень 1) на N тиков». */
#define LED_STEP_ON(ticks)   LED_STEP_LVL(1, (ticks))

/** Шаг «выключить (уровень 0) на N тиков». */
#define LED_STEP_OFF(ticks)  LED_STEP_LVL(0, (ticks))

/** Количество элементов в массиве (аргумент — имя массива). */
#define LED_ARRAY_LEN(arr) \
    ((uint16_t)(sizeof(arr) / sizeof((arr)[0])))

