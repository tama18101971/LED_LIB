/**
 * @file led.h
 * @brief Библиотека управления светодиодами для bare-metal микроконтроллеров (без RTOS).
 *
 * =====================================================================
 *  АРХИТЕКТУРА
 * =====================================================================
 *
 * Библиотека построена на принципе кооперативной многозадачности.
 * Весь код выполняется в одной функции led_process(), которую пользователь
 * вызывает с постоянной частотой (по умолчанию 60 Гц, 1 тик = 1/60 сек).
 *
 * Каждый светодиод имеет собственный конечный автомат (state machine),
 * который работает независимо от остальных. Это позволяет одновременно:
 *   - мигать одному диоду,
 *   - воспроизводить SOS на другом,
 *   - держать третий включённым на 5 секунд,
 *   - четвёртый — выключен.
 *
 * Глобальные эффекты (бегущий огонь, аварийная сигнализация и т.д.)
 * управляются через таблицу функций в led.c. Каждый эффект — функция,
 * возвращающая битовую маску желаемых состояний диодов.
 *
 * Последовательности (sequences) определяются статическими массивами
 * через макросы LED_STEP_ON() / LED_STEP_OFF(). Пример:
 *
 *   static const led_step_t my_seq[] = {
 *       LED_STEP_ON(10),   // включить на 10 тиков (167 мс)
 *       LED_STEP_OFF(5),   // выключить на 5 тиков (83 мс)
 *   };
 *   static const led_sequence_t seq = { my_seq, 2, true };  // зациклить
 *
 * =====================================================================
 *  МОДЕЛЬ ВЫЗОВОВ И ПОТОКОБЕЗОПАСНОСТЬ
 * =====================================================================
 *
 * Внутреннее состояние — обычные static-переменные без блокировок.
 * Поддерживаются два сценария:
 *
 *  1) ОДИН КОНТЕКСТ (по умолчанию). Все led_*() вызываются из одного
 *     места — обычно из главного цикла. Настройка не требуется.
 *
 *  2) led_process() В ПРЕРЫВАНИИ, остальной API — из главного цикла.
 *     Определите LED_ENTER_CRITICAL()/LED_EXIT_CRITICAL() (запрет и
 *     восстановление прерываний), чтобы мутаторы стали атомарными
 *     относительно обработчика. Пример для CH32V003 / RISC-V:
 *
 *       #define LED_ENTER_CRITICAL()  __disable_irq()
 *       #define LED_EXIT_CRITICAL()   __enable_irq()
 *
 *     Внимание: при заданных макросах пользовательский GPIO-callback
 *     может вызываться с запрещёнными прерываниями — держите его коротким.
 *
 *  НЕ ПОДДЕРЖИВАЕТСЯ: вызов мутаторов (led_on/led_blink/led_play/…) из
 *  прерывания, когда led_process() работает в главном цикле — состояние
 *  конечного автомата будет повреждено. led_process() критической
 *  секцией НЕ оборачивается намеренно: это сохраняет минимальную
 *  задержку реакции на прерывания.
 *
 * =====================================================================
 *  ОГРАНИЧЕНИЯ
 * =====================================================================
 *
 *   - Библиотека НЕ содержит код GPIO — доступ к ногам только через
 *     пользовательский callback (led_set_fn).
 *   - Нет malloc/free/рекурсии и зависимости от libc — только
 *     статическая память (~100 байт при LED_COUNT = 4).
 *   - led_process() выполняется за O(LED_COUNT) без переменных циклов.
 *   - Портабельность: C99, без расширений компилятора.
 *
 * =====================================================================
 *  СОВМЕСТИМОСТЬ
 * =====================================================================
 *
 *   Tested / designed for: STM32, CH32V003, AVR, ESP32.
 *   Любой bare-metal MCU с таймером или delay-функцией подходит.
 */

