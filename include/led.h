/*  ТИПЫ                                                               */
/* ================================================================== */

/**
 * Тип callback-функции для доступа к GPIO.
 *
 * Библиотека НЕ обращается к портам напрямую. Вместо этого она вызывает
 * эту функцию, когда состояние диода ИЗМЕНИЛОСЬ (внутренний кэш
 * отсекает повторные записи одного и того же уровня).
 *
 * Из callback нельзя вызывать функции led_*(): библиотека не реентерабельна.
 *
 * @param id     Индекс диода (0..LED_COUNT-1).
 * @param state  true = включить, false = выключить.
 *
 * Пример реализации для STM32:
 *   void led_hw_set(uint8_t id, bool state) {
 *       HAL_GPIO_WritePin(LED_PORT, led_pins[id],
 *                         state ? GPIO_PIN_SET : GPIO_PIN_RESET);
 *   }
 *
 * Пример для AVR:
 *   void led_hw_set(uint8_t id, bool state) {
 *       if (state) PORTB |= (1 << id);
 *       else       PORTB &= ~(1 << id);
 *   }
 */
typedef void (*led_set_fn)(uint8_t id, bool state);

/**
 * Режим работы конкретного светодиода (конечный автомат).
 *
 * Каждый диод находится ровно в одном из этих режимов.
 *
 *   LED_MODE_OFF      — принудительно выключен
 *   LED_MODE_ON       — принудительно включён
 *   LED_MODE_ON_FOR   — включён на N тиков, потом авто-выключение
 *   LED_MODE_BLINK    — непрерывное мигание (on M тиков / off N тиков)
 *   LED_MODE_SEQUENCE — воспроизведение пользовательской последовательности
 *   LED_MODE_EFFECT   — управление глобальным эффектом
 */
typedef enum {
    LED_MODE_OFF      = 0,
    LED_MODE_ON       = 1,
    LED_MODE_ON_FOR   = 2,
    LED_MODE_BLINK    = 3,
    LED_MODE_SEQUENCE = 4,
    LED_MODE_EFFECT   = 5
} led_mode_t;

/**
 * Встроенные глобальные эффекты.
 *
 * Глобальный эффект управляет ВСЕМИ диодами одновременно.
 * Активируется через led_start_effect(), останавливается
 * через led_stop_effect().
 *
 * При запуске эффекта все диоды переходят в режим LED_MODE_EFFECT.
 * Если пользователь вызовет led_on(id) на одном из диодов,
 * этот диод «оторвётся» от эффекта и будет управляться вручную,
 * а остальные продолжат эффект.
 *
 * Значения enum фиксированы и не зависят от LED_USE_*-настроек.
 */
typedef enum {
    LED_EFFECT_NONE             = 0,  /**< Эффект не активен                 */
    LED_EFFECT_RUNNING_FWD      = 1,  /**< Бегущий огонь вперёд (0→N-1)      */
    LED_EFFECT_RUNNING_BWD      = 2,  /**< Бегущий огонь назад (N-1→0)       */
    LED_EFFECT_RUNNING_PP       = 3,  /**< Бегущий огонь туда-обратно        */
    LED_EFFECT_RUNNING_CIRCLE   = 4,  /**< Вращение по кругу (быстрее FWD)   */
    LED_EFFECT_PAIR_BLINK       = 5,  /**< Попарное мигание (чёт/нечет)      */
    LED_EFFECT_EMERGENCY        = 6,  /**< Аварийная сигнализация (все)      */
    LED_EFFECT_RANDOM_FLASH     = 7,  /**< Случайные вспышки (xorshift32)    */
    LED_EFFECT_DOUBLE_BLINK     = 8,  /**< Двойное мигание                   */
    LED_EFFECT_TRIPLE_BLINK     = 9,  /**< Тройное мигание                   */
    LED_EFFECT_ALTERNATING      = 10, /**< Чередование чёт/нечёт (медленно)  */
    LED_EFFECT_RUNNING_FWD_HOLD = 11, /**< Бег вперёд + пауза + удержание    */
    LED_EFFECT_RUNNING_BWD_HOLD = 12, /**< Бег назад + пауза + удержание     */
    LED_EFFECT_COUNT            = 13  /**< Количество значений (граница)     */
} led_effect_t;

/**
 * Значение «эффект работает бесконечно», возвращаемое
 * led_effect_remaining().
 */
#define LED_EFFECT_FOREVER 0xFFFFFFFFu

/**
 * Один шаг последовательности: состояние + длительность.
 *
 * Пример: «включить на 10 тиков, выключить на 5 тиков»
 *   { true,  10 }   // LED_STEP_ON(10)
 *   { false,  5 }   // LED_STEP_OFF(5)
 *
 * Шаг с ticks == 0 трактуется как 1 тик (нулевая длительность
 * невозможна в тиковой модели).
 */
typedef struct {
    bool     state;   /**< true = включить, false = выключить      */
    uint16_t ticks;   /**< Длительность в тиках (0 → 1)            */
} led_step_t;

/**
 * Определение последовательности.
 *
 * ВАЖНО: библиотека хранит указатель на массив steps и не копирует его.
 * Массив должен существовать всё время воспроизведения — используйте
 * static/const, а не локальные переменные.
 *
 * Пример (SOS):
 *   static const led_step_t sos[] = {
 *       LED_STEP_ON(6),  LED_STEP_OFF(6),    // .
 *       LED_STEP_ON(6),  LED_STEP_OFF(6),    // .
 *       LED_STEP_ON(6),  LED_STEP_OFF(18),   // . (пауза)
 *       LED_STEP_ON(18), LED_STEP_OFF(6),    // -
 *       ...
 *   };
 *   static const led_sequence_t sos_seq = {
 *       sos, sizeof(sos) / sizeof(sos[0]), true
 *   };
 *   led_play(2, &sos_seq);  // воспроизвести на LED2
 */
typedef struct {
    const led_step_t *steps;   /**< Массив шагов (должен «жить» долго) */
    uint16_t          count;   /**< Количество шагов                  */
    bool              loop;    /**< true = зациклить                  */
} led_sequence_t;

